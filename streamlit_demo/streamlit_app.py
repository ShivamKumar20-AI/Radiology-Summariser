"""Free Streamlit version of the Radiology Summariser demo.

Same model and same limits as the FastAPI service in src/, but hosted on Streamlit Community Cloud.
Prototype: not pushed or deployed yet.
"""
import os
import sys
import threading
import time
from pathlib import Path

import streamlit as st

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.guards import (  # noqa: E402
    MAX_CONCURRENT_SUMMARIES, MAX_FINDINGS_CHARS, MAX_REQUESTS_ALL_PER_MIN, SlidingWindowLimiter,
)

MODEL_DIR = ROOT / "model" / "final"
HF_REPO = os.getenv("MODEL_HF_REPO")           # e.g. "username/radiology-summariser-t5" (private is fine)
MAX_REQUESTS_PER_SESSION_PER_MIN = 5

st.set_page_config(page_title="Radiology Summariser", page_icon="🩻")
st.title("Radiology Summariser")
st.caption("Clinical AI prototype: turns radiology findings into a short impression. Not for clinical use.")


@st.cache_resource(show_spinner="Loading the model (first visit takes a minute)...")
def load_model():
    import torch
    from transformers import AutoModelForSeq2SeqLM, AutoTokenizer

    path = str(MODEL_DIR) if (MODEL_DIR / "config.json").exists() else None
    if path is None:
        from huggingface_hub import snapshot_download
        path = snapshot_download(HF_REPO, token=os.getenv("HF_TOKEN"))
    torch.set_num_threads(2)
    tokenizer = AutoTokenizer.from_pretrained(path)
    model = AutoModelForSeq2SeqLM.from_pretrained(path).eval()
    return tokenizer, model


@st.cache_resource
def shared_state():
    return SlidingWindowLimiter(MAX_REQUESTS_ALL_PER_MIN), threading.BoundedSemaphore(MAX_CONCURRENT_SUMMARIES)


def allowed_this_session() -> bool:
    now = time.time()
    recent = [t for t in st.session_state.get("times", []) if now - t < 60]
    st.session_state.times = recent
    if len(recent) >= MAX_REQUESTS_PER_SESSION_PER_MIN:
        return False
    recent.append(now)
    return True


def summarise(findings: str) -> str:
    import torch

    tokenizer, model = load_model()
    inputs = tokenizer("summarize radiology findings: " + findings, max_length=512, truncation=True, return_tensors="pt")
    with torch.no_grad():
        output = model.generate(**inputs, max_length=128, num_beams=4)
    return tokenizer.decode(output[0], skip_special_tokens=True)


st.info("This is a demo. Do not paste real patient information. Nothing you type is stored.")
findings = st.text_area("Clinical findings", max_chars=MAX_FINDINGS_CHARS, height=180,
                        placeholder="Example: The lungs are clear. Heart size and mediastinal contours are normal.")

if st.button("Generate impression", type="primary"):
    text = findings.strip()
    limiter, slots = shared_state()
    if not text:
        st.error("Please enter some findings.")
    elif len(text) > MAX_FINDINGS_CHARS:
        st.error(f"Too long (limit {MAX_FINDINGS_CHARS} characters).")
    elif not allowed_this_session() or not limiter.allow():
        st.error("Too many requests. Please wait a minute and try again.")
    elif not slots.acquire(blocking=False):
        st.error("The service is busy. Please try again in a moment.")
    else:
        try:
            with st.spinner("Analysing findings..."):
                started = time.time()
                impression = summarise(text)
            print(f"summary ok chars={len(text)} seconds={time.time() - started:.1f}")  # size and timing only
            st.subheader("AI-generated impression")
            st.success(impression)
            st.caption("Generated by a small model that often reports normal results. Always check with a qualified professional.")
        except Exception as exc:
            print(f"summary failed: {type(exc).__name__}")
            st.error("Something went wrong. Please try again.")
        finally:
            slots.release()
